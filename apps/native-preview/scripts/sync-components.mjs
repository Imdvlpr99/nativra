#!/usr/bin/env node
/**
 * Copies the StyleSheet implementation of every registry component, block and template, plus
 * the use-theme-colors hook and every theme, into apps/native-preview/components/nativra, so the
 * preview app runs the exact source the CLI installs. The preview app has no path aliases, so
 * registry aliases are rewritten to sibling imports.
 *
 * Generated alongside the copies:
 *   preview-env.ts  reads ?theme= and ?scheme= from the URL (web) and provides useColorScheme,
 *                   so an embedding page (the docs site) controls the theme and light/dark mode
 *   theme.ts        the active theme, chosen from ?theme= (default: zinc)
 *   style.ts        the active style, chosen from ?style= (default: soft)
 *   items.ts        registry id -> component, for every component, block and template
 */
import { mkdir, readdir, readFile, rm, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const registry = resolve(here, "../../../registry/default");
const out = resolve(here, "../components/nativra");
await rm(out, { recursive: true, force: true });
await mkdir(join(out, "themes"), { recursive: true });

/** Registry aliases -> sibling files; useColorScheme -> the URL-aware preview version. */
function rewrite(src) {
  let s = src
    .replace(/(from\s+["'])@\/components\/ui\//g, "$1./")
    .replace(/(from\s+["'])@\/blocks\//g, "$1./")
    .replace(/(from\s+["'])@\/hooks\//g, "$1./")
    .replace(/(from\s+["'])@\/lib\/themes\//g, "$1./");
  const rn = /import\s*\{([^}]*)\}\s*from\s*["']react-native["'];?/;
  const m = rn.exec(s);
  if (m && /\buseColorScheme\b/.test(m[1])) {
    const rest = m[1].split(",").map((x) => x.trim()).filter((x) => x && x !== "useColorScheme");
    const replacement =
      (rest.length ? `import { ${rest.join(", ")} } from "react-native";\n` : "") +
      `import { useColorScheme } from "./preview-env";`;
    s = s.replace(m[0], replacement);
  }
  return s;
}

const write = (name, content) => writeFile(join(out, name), content, "utf8");
const copy = async (from, name) => write(name, rewrite(await readFile(from, "utf8")));

await write(
  "preview-env.ts",
  `/** Generated by scripts/sync-components.mjs. URL overrides for the embeddable preview (web only). */
import { Platform, useColorScheme as useSystemColorScheme } from "react-native";

const params =
  Platform.OS === "web" && typeof window !== "undefined" ? new URLSearchParams(window.location.search) : null;

/** Theme id from ?theme=, or null for the default. */
export const PREVIEW_THEME = params?.get("theme") ?? null;
/** Style id from ?style=, or null for the default. */
export const PREVIEW_STYLE = params?.get("style") ?? null;
const forcedScheme = params?.get("scheme");

/** The device color scheme, unless ?scheme=light|dark forces one. */
export function useColorScheme(): "light" | "dark" | null | undefined {
  const system = useSystemColorScheme();
  return forcedScheme === "dark" || forcedScheme === "light" ? forcedScheme : system;
}
`
);
await copy(join(registry, "hooks/use-theme-colors/use-theme-colors.ts"), "use-theme-colors.ts");

// Every theme, plus a theme.ts that picks one from the URL.
const themeIds = (await readdir(join(registry, "themes"))).sort();
for (const id of themeIds) await copy(join(registry, "themes", id, "theme.ts"), `themes/${id}.ts`);
const ident = (id) => `t_${id.replace(/-/g, "_")}`;
await write(
  "theme.ts",
  `/** Generated by scripts/sync-components.mjs: the active theme, chosen with ?theme=<id> (default: zinc). */
${themeIds.map((id) => `import * as ${ident(id)} from "./themes/${id}";`).join("\n")}
import { PREVIEW_THEME } from "./preview-env";

type Theme = { themeColors: typeof ${ident("zinc")}.themeColors };
const PRESETS: Record<string, Theme> = {
${themeIds.map((id) => `  "${id}": ${ident(id)} as unknown as Theme,`).join("\n")}
};
const active = PRESETS[PREVIEW_THEME ?? ""] ?? PRESETS["zinc"]!;

export const themeColors = active.themeColors;
export const THEME_IDS = ${JSON.stringify(themeIds)} as const;
`
);

// Every style, plus a style.ts that picks one from the URL.
await mkdir(join(out, "styles"), { recursive: true });
const styleIds = (await readdir(join(registry, "styles"))).sort();
for (const id of styleIds) await copy(join(registry, "styles", id, "style.ts"), `styles/${id}.ts`);
const sident = (id) => `s_${id.replace(/-/g, "_")}`;
await write(
  "style.ts",
  `/** Generated by scripts/sync-components.mjs: the active style, chosen with ?style=<id> (default: soft). */
${styleIds.map((id) => `import * as ${sident(id)} from "./styles/${id}";`).join("\n")}
import { PREVIEW_STYLE } from "./preview-env";

type Style = { themeStyle: typeof ${sident("soft")}.themeStyle };
const PRESETS: Record<string, Style> = {
${styleIds.map((id) => `  "${id}": ${sident(id)} as unknown as Style,`).join("\n")}
};

export const themeStyle = (PRESETS[PREVIEW_STYLE ?? ""] ?? PRESETS["soft"]!).themeStyle;
export const STYLE_IDS = ${JSON.stringify(styleIds)} as const;
`
);

// Components, blocks and templates (StyleSheet target).
const componentNames = [];
const items = []; // [id, type, exportName]
for (const type of ["components", "blocks", "templates"]) {
  for (const entry of (await readdir(join(registry, type))).sort()) {
    const itemDir = join(registry, type, entry);
    let item;
    try {
      item = JSON.parse(await readFile(join(itemDir, "item.json"), "utf8"));
    } catch {
      continue;
    }
    for (const f of item.files ?? []) {
      if (f.target && f.target !== "stylesheet") continue;
      const fileName = f.path.split("/").pop();
      const name = fileName.replace(/\.tsx?$/, "");
      const src = await readFile(resolve(itemDir, f.path), "utf8");
      await write(fileName, rewrite(src));
      if (type === "components") componentNames.push(name);
      if (new RegExp(`export (function|const|class) ${name}\\b`).test(src)) items.push([item.id, type, name]);
      else console.warn(`  ! ${item.id}: no "${name}" export, so it can't be previewed`);
    }
  }
}

await write("index.ts", componentNames.map((n) => `export * from "./${n}";`).join("\n") + "\n");
await write(
  "items.ts",
  `/** Generated by scripts/sync-components.mjs: registry id -> component, for the embeddable preview. */
import type { ComponentType } from "react";
${items.map(([, , name]) => `import { ${name} } from "./${name}";`).join("\n")}

export type PreviewItemType = "component" | "block" | "template";

// eslint-disable-next-line @typescript-eslint/no-explicit-any -- each item has its own props; fixtures supply them
export const ITEMS: Record<string, { type: PreviewItemType; Component: ComponentType<any> }> = {
${items.map(([id, type, name]) => `  "${id}": { type: "${type.replace(/s$/, "")}", Component: ${name} },`).join("\n")}
};
`
);
console.log(
  `Synced ${componentNames.length} components, ${items.length - componentNames.length} blocks/templates, ${themeIds.length} themes, ${styleIds.length} styles`
);
