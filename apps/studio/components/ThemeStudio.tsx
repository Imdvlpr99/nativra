'use client';

import React, { useState } from 'react';
import { Palette, Copy, Check, Sun, Moon, RefreshCw } from 'lucide-react';

interface ThemeTokenState {
  name: string;
  primary: string;
  primaryFg: string;
  background: string;
  card: string;
  accent: string;
  muted: string;
  destructive: string;
  radius: number;
}

const PRESET_THEMES: Record<string, ThemeTokenState> = {
  zinc: {
    name: 'Zinc Dark',
    primary: '#18181b',
    primaryFg: '#ffffff',
    background: '#09090b',
    card: '#18181b',
    accent: '#3b82f6',
    muted: '#71717a',
    destructive: '#ef4444',
    radius: 12,
  },
  ocean: {
    name: 'Ocean Blue',
    primary: '#0284c7',
    primaryFg: '#ffffff',
    background: '#0f172a',
    card: '#1e293b',
    accent: '#38bdf8',
    muted: '#64748b',
    destructive: '#f43f5e',
    radius: 14,
  },
  emerald: {
    name: 'Emerald Forest',
    primary: '#059669',
    primaryFg: '#ffffff',
    background: '#064e3b',
    card: '#065f46',
    accent: '#34d399',
    muted: '#6ee7b7',
    destructive: '#f87171',
    radius: 12,
  },
  midnight: {
    name: 'Midnight Purple',
    primary: '#7c3aed',
    primaryFg: '#ffffff',
    background: '#0b071a',
    card: '#1a103c',
    accent: '#c084fc',
    muted: '#8b5cf6',
    destructive: '#f43f5e',
    radius: 16,
  },
};

const DEFAULT_THEME_STATE: ThemeTokenState = PRESET_THEMES.zinc ?? {
  name: 'Zinc Dark',
  primary: '#18181b',
  primaryFg: '#ffffff',
  background: '#09090b',
  card: '#18181b',
  accent: '#3b82f6',
  muted: '#71717a',
  destructive: '#ef4444',
  radius: 12,
};

export function ThemeStudio() {
  const [theme, setTheme] = useState<ThemeTokenState>(DEFAULT_THEME_STATE);
  const [isDark, setIsDark] = useState(true);
  const [activeTab, setActiveTab] = useState<'preview' | 'tailwind' | 'stylesheet'>('preview');
  const [copied, setCopied] = useState(false);

  const applyPreset = (key: string) => {
    const preset = PRESET_THEMES[key];
    if (preset) {
      setTheme(preset);
    }
  };

  const updateToken = (key: keyof ThemeTokenState, val: string | number) => {
    setTheme((prev) => ({ ...prev, [key]: val }));
  };

  const generateTailwindConfig = () => {
    return `// tailwind.config.js - Generated by Nativra Theme Engine
/** @type {import('tailwindcss').Config} */
module.exports = {
  content: ["./app/**/*.{js,jsx,ts,tsx}", "./components/**/*.{js,jsx,ts,tsx}"],
  presets: [require("nativewind/preset")],
  theme: {
    extend: {
      colors: {
        primary: "${theme.primary}",
        "primary-foreground": "${theme.primaryFg}",
        background: "${theme.background}",
        card: "${theme.card}",
        accent: "${theme.accent}",
        muted: "${theme.muted}",
        destructive: "${theme.destructive}",
      },
      borderRadius: {
        theme: "${theme.radius}px",
      },
    },
  },
  plugins: [],
};`;
  };

  const generateStyleSheetTheme = () => {
    return `// theme.ts - Generated by Nativra Theme Engine
export const theme = {
  colors: {
    primary: "${theme.primary}",
    primaryForeground: "${theme.primaryFg}",
    background: "${theme.background}",
    card: "${theme.card}",
    accent: "${theme.accent}",
    muted: "${theme.muted}",
    destructive: "${theme.destructive}",
  },
  radius: {
    sm: ${Math.max(2, theme.radius - 6)},
    md: ${theme.radius},
    lg: ${theme.radius + 6},
    full: 9999,
  },
  space: {
    xs: 4,
    sm: 8,
    md: 16,
    lg: 24,
    xl: 32,
  },
} as const;

export type Theme = typeof theme;`;
  };

  const copyCode = (code: string) => {
    navigator.clipboard.writeText(code);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  return (
    <div className="flex flex-1 overflow-hidden h-full">
      {/* Left: Token Inspector & Presets */}
      <aside className="w-80 shrink-0 flex flex-col border-r border-zinc-800 bg-zinc-900/70 p-4 space-y-5 overflow-y-auto">
        <div className="flex items-center justify-between border-b border-zinc-800 pb-3">
          <div className="flex items-center gap-2">
            <Palette className="h-4 w-4 text-sky-400" />
            <span className="text-xs font-bold text-white">Theme Tokens</span>
          </div>
          <button
            type="button"
            onClick={() => setTheme(DEFAULT_THEME_STATE)}
            className="flex items-center gap-1 text-[10px] text-zinc-400 hover:text-white"
          >
            <RefreshCw className="h-3 w-3" />
            <span>Reset</span>
          </button>
        </div>

        {/* Theme Presets */}
        <div>
          <span className="text-[10px] font-semibold uppercase tracking-wider text-zinc-500 mb-2 block">
            Color Presets
          </span>
          <div className="grid grid-cols-2 gap-2">
            {Object.entries(PRESET_THEMES).map(([k, p]) => (
              <button
                key={k}
                type="button"
                onClick={() => applyPreset(k)}
                className={`flex items-center gap-2 rounded-xl border p-2 text-left text-xs transition-all ${
                  theme.name === p.name
                    ? 'border-sky-500 bg-sky-500/10 text-white shadow-sm'
                    : 'border-zinc-800 bg-zinc-950/60 text-zinc-400 hover:border-zinc-700'
                }`}
              >
                <div
                  style={{ backgroundColor: p.primary }}
                  className="h-4 w-4 rounded-md shadow-sm border border-white/20 shrink-0"
                />
                <span className="truncate text-[11px] font-medium">{p.name}</span>
              </button>
            ))}
          </div>
        </div>

        {/* Token Color Controls */}
        <div className="space-y-3">
          <span className="text-[10px] font-semibold uppercase tracking-wider text-zinc-500 block">
            Color Palettes
          </span>

          {[
            { label: 'Primary Brand', key: 'primary' as const },
            { label: 'Accent / Highlight', key: 'accent' as const },
            { label: 'Background', key: 'background' as const },
            { label: 'Card Surface', key: 'card' as const },
            { label: 'Destructive', key: 'destructive' as const },
          ].map(({ label, key }) => (
            <div key={key} className="flex items-center justify-between">
              <span className="text-xs text-zinc-300">{label}</span>
              <div className="flex items-center gap-2">
                <input
                  type="color"
                  value={theme[key]}
                  onChange={(e) => updateToken(key, e.target.value)}
                  className="h-7 w-7 rounded border-0 bg-transparent cursor-pointer"
                />
                <span className="text-[11px] font-mono text-zinc-400 uppercase w-16">
                  {theme[key]}
                </span>
              </div>
            </div>
          ))}
        </div>

        {/* Border Radius Slider */}
        <div className="pt-3 border-t border-zinc-800">
          <div className="flex items-center justify-between mb-1.5">
            <span className="text-xs text-zinc-300">Base Border Radius</span>
            <span className="text-xs font-mono text-sky-400 font-bold">{theme.radius}px</span>
          </div>
          <input
            type="range"
            min="0"
            max="28"
            step="2"
            value={theme.radius}
            onChange={(e) => updateToken('radius', Number(e.target.value))}
            className="w-full h-1.5 bg-zinc-800 rounded-lg appearance-none cursor-pointer accent-sky-500"
          />
        </div>
      </aside>

      {/* Center: Live Theme Preview & Export Code */}
      <main className="flex-1 flex flex-col items-center justify-center relative p-6 bg-zinc-950 bg-dot-grid overflow-y-auto">
        {/* Navigation Toolbar */}
        <div className="absolute top-4 left-6 z-10 flex items-center gap-2">
          <div className="flex rounded-xl border border-zinc-800 bg-zinc-900/90 p-1 text-xs backdrop-blur shadow-lg">
            <button
              onClick={() => setActiveTab('preview')}
              className={`rounded-lg px-3 py-1 font-medium transition-colors ${
                activeTab === 'preview' ? 'bg-zinc-800 text-white' : 'text-zinc-400 hover:text-zinc-200'
              }`}
            >
              Component Preview
            </button>
            <button
              onClick={() => setActiveTab('tailwind')}
              className={`rounded-lg px-3 py-1 font-medium transition-colors ${
                activeTab === 'tailwind' ? 'bg-zinc-800 text-white' : 'text-zinc-400 hover:text-zinc-200'
              }`}
            >
              tailwind.config.js
            </button>
            <button
              onClick={() => setActiveTab('stylesheet')}
              className={`rounded-lg px-3 py-1 font-medium transition-colors ${
                activeTab === 'stylesheet' ? 'bg-zinc-800 text-white' : 'text-zinc-400 hover:text-zinc-200'
              }`}
            >
              theme.ts
            </button>
          </div>

          <button
            onClick={() => setIsDark(!isDark)}
            title="Toggle Light / Dark mode"
            className="flex items-center gap-1.5 rounded-xl border border-zinc-800 bg-zinc-900/90 px-3 py-1.5 text-xs text-zinc-300 hover:text-white backdrop-blur shadow-sm"
          >
            {isDark ? <Moon className="h-3.5 w-3.5 text-sky-400" /> : <Sun className="h-3.5 w-3.5 text-amber-400" />}
            <span>{isDark ? 'Dark Mode' : 'Light Mode'}</span>
          </button>
        </div>

        {activeTab === 'preview' ? (
          /* Live Theme Specimen Card */
          <div
            style={{
              backgroundColor: isDark ? theme.background : '#ffffff',
              borderRadius: `${theme.radius + 6}px`,
            }}
            className="w-[393px] border border-zinc-800 p-6 shadow-2xl space-y-5 transition-all my-auto"
          >
            <div className="flex items-center justify-between border-b border-zinc-800/80 pb-3">
              <div>
                <h3 className="text-base font-bold text-white">{theme.name}</h3>
                <p className="text-xs text-zinc-400">Design token specimen</p>
              </div>
              <span
                style={{ backgroundColor: theme.primary, color: theme.primaryFg }}
                className="rounded-full px-2.5 py-0.5 text-[10px] font-semibold shadow-sm"
              >
                Active
              </span>
            </div>

            {/* Specimen Card */}
            <div
              style={{
                backgroundColor: theme.card,
                borderRadius: `${theme.radius}px`,
              }}
              className="p-4 border border-white/10 shadow-lg space-y-3"
            >
              <div className="flex items-center justify-between">
                <span className="text-xs font-bold text-white">Subscription Pro</span>
                <span
                  style={{ color: theme.accent }}
                  className="text-xs font-extrabold"
                >
                  $19 / mo
                </span>
              </div>
              <p className="text-xs text-zinc-400 leading-relaxed">
                Tokens apply universally across NativeWind utility classes and StyleSheet theme objects.
              </p>
              <button
                type="button"
                style={{
                  backgroundColor: theme.primary,
                  color: theme.primaryFg,
                  borderRadius: `${theme.radius}px`,
                }}
                className="w-full py-2.5 text-xs font-semibold shadow-sm active:scale-95 transition-transform"
              >
                Get Started Free
              </button>
            </div>

            {/* Secondary Action & Badges */}
            <div className="flex items-center justify-between pt-2">
              <span
                style={{
                  backgroundColor: `${theme.accent}20`,
                  color: theme.accent,
                  borderRadius: `${theme.radius}px`,
                }}
                className="px-2.5 py-1 text-[11px] font-semibold"
              >
                Accent Badge
              </span>
              <button
                type="button"
                style={{
                  backgroundColor: theme.destructive,
                  borderRadius: `${theme.radius}px`,
                }}
                className="px-3 py-1.5 text-xs font-semibold text-white shadow-sm"
              >
                Delete Account
              </button>
            </div>
          </div>
        ) : (
          /* Generated Code View */
          <div className="w-full max-w-2xl h-[650px] rounded-2xl border border-zinc-800 bg-zinc-900 shadow-2xl flex flex-col overflow-hidden my-auto">
            <div className="flex h-11 items-center justify-between border-b border-zinc-800 bg-zinc-950 px-4">
              <span className="text-xs font-mono text-zinc-400">
                {activeTab === 'tailwind' ? 'tailwind.config.js' : 'src/theme/theme.ts'}
              </span>
              <button
                type="button"
                onClick={() =>
                  copyCode(activeTab === 'tailwind' ? generateTailwindConfig() : generateStyleSheetTheme())
                }
                className="flex items-center gap-1.5 rounded-lg bg-zinc-800 px-2.5 py-1 text-xs font-medium text-white hover:bg-zinc-700 transition-colors"
              >
                {copied ? <Check className="h-3.5 w-3.5 text-emerald-400" /> : <Copy className="h-3.5 w-3.5" />}
                <span>{copied ? 'Copied!' : 'Copy Config'}</span>
              </button>
            </div>
            <pre className="flex-1 overflow-auto p-4 text-xs font-mono text-zinc-300 leading-relaxed bg-zinc-950/60">
              <code>{activeTab === 'tailwind' ? generateTailwindConfig() : generateStyleSheetTheme()}</code>
            </pre>
          </div>
        )}
      </main>
    </div>
  );
}
